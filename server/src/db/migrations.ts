/** Advisory lock that keeps two server instances from migrating at the same time. */
const MIGRATION_LOCK = 7_306_000;

export async function migrate(driver: Driver): Promise<void> {
  await driver.withConnection(async (connection) => {
    await connection.query('BEGIN', []);
    try {
      await connection.query('SELECT pg_advisory_xact_lock($1)', [MIGRATION_LOCK]);
      await connection.exec(`
        CREATE TABLE IF NOT EXISTS schema_migrations (
          version    BIGINT PRIMARY KEY,
          name       TEXT NOT NULL,
          applied_at TEXT NOT NULL
        )
      `);
      const applied = new Set(
        (await connection.query<{ version: number }>('SELECT version FROM schema_migrations', [])).rows.map((row) => row.version),
      );
      for (const migration of migrations) {
        if (applied.has(migration.version)) continue;
        await connection.exec(migration.sql);
        await connection.query('INSERT INTO schema_migrations (version, name, applied_at) VALUES ($1, $2, $3)', [
          migration.version,
          migration.name,
          new Date().toISOString(),
        ]);
      }
      await connection.query('COMMIT', []);
    } catch (err) {
      await connection.query('ROLLBACK', []).catch(() => {});
      throw err;
    }
  });
}
